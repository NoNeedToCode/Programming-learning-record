import numpy as np

a=np.arange(2,14).reshape((3,4))
b=np.arange(13,1,-1).reshape((3,4))
print(a,"\n",b)
print(np.argmax(a,axis=0))
print(np.argmin(a))
print(np.mean(a))
print(a.mean())
print(np.average(a,weights=b))
print(np.median(a))
print(np.cumsum(a))
print(np.diff(a))
print(np.nonzero(a))
print(np.sort(b).reshape((4,3)))
print(np.transpose(a))
print(a.T)
print(a.T.dot(a))
print(b)
print(np.clip(b,3,7))
